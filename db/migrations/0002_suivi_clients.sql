-- ───────────────────────── Tickets ──────────────────────────────────────
-- Un ticket appartient toujours à un client (une fiche de public.prospects).
create table public.tickets (
  id                 uuid primary key default gen_random_uuid(),
  number             int generated by default as identity (start with 1001) unique,
  prospect_id        uuid not null references public.prospects(id) on delete cascade,
  project_id         uuid references public.projects(id) on delete set null,
  subject            text not null check (length(trim(subject)) > 0),
  description        text,
  type               text not null default 'demande' check (type in ('demande','incident','question','facturation','autre')),
  channel            text check (channel in ('telephone','whatsapp','email','instagram','sur_place','autre')),
  priority           text not null default 'normale' check (priority in ('basse','normale','haute','urgente')),
  status             text not null default 'nouveau' check (status in ('nouveau','en_cours','attente_client','resolu','ferme')),
  assignee_id        uuid references public.profiles(id) on delete set null,
  due_date           date,
  status_changed_at  timestamptz not null default now(),
  resolved_at        timestamptz,
  created_by         uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create index tickets_status_idx on public.tickets (status);
create index tickets_prospect_idx on public.tickets (prospect_id);
create index tickets_assignee_idx on public.tickets (assignee_id);

-- Les commentaires et fichiers polymorphes acceptent les tickets ;
-- un commentaire avec un canal est un échange avec le client, sans canal une note interne.
alter table public.comments drop constraint comments_entity_type_check;
alter table public.comments add constraint comments_entity_type_check
  check (entity_type in ('prospect','project','revision','task','ticket'));
alter table public.comments add column channel text
  check (channel in ('telephone','whatsapp','email','instagram','sur_place','autre'));

alter table public.attachments drop constraint attachments_entity_type_check;
alter table public.attachments add constraint attachments_entity_type_check
  check (entity_type in ('prospect','project','revision','task','ticket'));

alter table public.status_history drop constraint status_history_entity_type_check;
alter table public.status_history add constraint status_history_entity_type_check
  check (entity_type in ('prospect','project','ticket'));

alter table public.activities add column ticket_id uuid references public.tickets(id) on delete cascade;
create index activities_ticket_idx on public.activities (ticket_id);

-- ═══════════════════════════ Triggers métier ═══════════════════════════
create trigger tickets_touch before update on public.tickets for each row execute function touch_updated_at();

-- Numéro figé ; dates de changement de statut et de résolution écrites par la base
create or replace function public.stamp_ticket() returns trigger language plpgsql as $$
begin
  if tg_op = 'UPDATE' then
    new.number := old.number;
    new.created_at := old.created_at;
  end if;
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    new.status_changed_at := now();
  end if;
  if new.status in ('resolu','ferme') then
    if tg_op = 'INSERT' or old.status not in ('resolu','ferme') then new.resolved_at := now(); end if;
  else
    new.resolved_at := null;
  end if;
  return new;
end $$;
create trigger tickets_stamp before insert or update on public.tickets for each row execute function stamp_ticket();

-- Tickets → historique des statuts + fil d'activité
create or replace function public.log_ticket() returns trigger
language plpgsql security definer set search_path = public as $$
declare t text; client text; dest text;
begin
  select name into client from prospects where id = new.prospect_id;
  if tg_op = 'INSERT' then
    insert into status_history (entity_type, entity_id, from_status, to_status, changed_by)
      values ('ticket', new.id, null, new.status, auth.uid());
    insert into activities (type, actor_id, prospect_id, project_id, ticket_id, meta)
      values ('ticket_opened', auth.uid(), new.prospect_id, new.project_id, new.id,
              jsonb_build_object('name', client, 'number', new.number, 'subject', new.subject));
    return new;
  end if;
  if new.status is distinct from old.status then
    insert into status_history (entity_type, entity_id, from_status, to_status, changed_by)
      values ('ticket', new.id, old.status, new.status, auth.uid());
    t := case when new.status = 'resolu' then 'ticket_resolved'
              when old.status in ('resolu','ferme') and new.status not in ('resolu','ferme') then 'ticket_reopened'
              else 'ticket_status' end;
    insert into activities (type, actor_id, prospect_id, project_id, ticket_id, meta)
      values (t, auth.uid(), new.prospect_id, new.project_id, new.id,
              jsonb_build_object('name', client, 'number', new.number, 'subject', new.subject, 'from', old.status, 'to', new.status));
  end if;
  if new.assignee_id is distinct from old.assignee_id then
    select first_name into dest from profiles where id = new.assignee_id;
    insert into activities (type, actor_id, prospect_id, project_id, ticket_id, meta)
      values ('ticket_assigned', auth.uid(), new.prospect_id, new.project_id, new.id,
              jsonb_build_object('name', client, 'number', new.number, 'subject', new.subject, 'to', new.assignee_id, 'to_name', dest));
  end if;
  return new;
end $$;
create trigger tickets_log after insert or update on public.tickets for each row execute function log_ticket();

-- Échange avec le client (commentaire avec canal) → fil d'activité de l'équipe
create or replace function public.log_contact() returns trigger
language plpgsql security definer set search_path = public as $$
declare k record;
begin
  if new.channel is null then return new; end if;
  if new.entity_type = 'ticket' then
    select t.prospect_id, t.project_id, t.id as ticket_id, t.number, p.name into k
      from tickets t join prospects p on p.id = t.prospect_id where t.id = new.entity_id;
  elsif new.entity_type = 'prospect' then
    select p.id as prospect_id, null::uuid as project_id, null::uuid as ticket_id, null::int as number, p.name into k
      from prospects p where p.id = new.entity_id;
  else
    return new;
  end if;
  if k.prospect_id is null then return new; end if;
  insert into activities (type, actor_id, prospect_id, project_id, ticket_id, meta)
    values ('contact_logged', auth.uid(), k.prospect_id, k.project_id, k.ticket_id,
            jsonb_build_object('name', k.name, 'channel', new.channel, 'number', k.number));
  return new;
end $$;
create trigger comments_contact after insert on public.comments for each row execute function log_contact();

-- La suppression définitive d'un dossier emporte ses commentaires, fichiers et historique
-- (ces tables sont polymorphes : aucune clé étrangère ne le ferait à leur place).
create or replace function public.purge_entity() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  delete from comments where entity_type = tg_argv[0] and entity_id = old.id;
  delete from attachments where entity_type = tg_argv[0] and entity_id = old.id;
  delete from status_history where entity_type = tg_argv[0] and entity_id = old.id;
  return old;
end $$;
create trigger prospects_purge after delete on public.prospects for each row execute function purge_entity('prospect');
create trigger projects_purge  after delete on public.projects  for each row execute function purge_entity('project');
create trigger revisions_purge after delete on public.revisions for each row execute function purge_entity('revision');
create trigger tasks_purge     after delete on public.tasks     for each row execute function purge_entity('task');
create trigger tickets_purge   after delete on public.tickets   for each row execute function purge_entity('ticket');

